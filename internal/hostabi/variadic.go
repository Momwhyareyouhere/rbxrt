package hostabi

import (
	"fmt"
	"unsafe"
)

// Variadic host functions. A thunk cannot know a variadic guest call's argument
// types, so the thunk instead sets R10 to a function id and jumps to
// variadicEntry (see abi_amd64.s), which saves the complete SysV variadic state
// and calls goVariadic. goVariadic then reconstructs a va_list from that state
// and reuses the same formatter as vsnprintf.

// variadicEntryAddr and variadicEntry are implemented in assembly.
// variadicEntryAddr publishes the raw ABI0 body of variadicEntry, which is the
// correct JMP target for a variadic thunk: taking variadicEntry's address from
// Go would instead yield the autogenerated wrapper, whose extra stack frame
// would shift the guest's overflow area.
func variadicEntryAddr() uintptr

// variadicTarget holds goVariadic's ABIInternal entry point. variadicEntry must
// call it with register arguments, but a direct symbol reference from assembly
// binds to the ABI0 (stack argument) wrapper, so the address is published here.
var variadicTarget uintptr

func init() { variadicTarget = funcAddr(goVariadic) }

const (
	vkPrintf = iota
	vkFprintf
	vkSnprintf
	vkSprintf
	vkSscanf
	vkFscanf
	vkScanf
	vkSyslog
)

// varDesc describes one variadic function: how many fixed integer arguments
// precede the format string (or stream+format) and how the output is routed.
type varDesc struct {
	kind    int
	fixedGP int
}

var variadicDescs = []varDesc{
	{vkSnprintf, 3}, // snprintf(str, size, fmt, ...)
	{vkSprintf, 2},  // sprintf(str, fmt, ...)
	{vkPrintf, 1},   // printf(fmt, ...)
	{vkFprintf, 2},  // fprintf(stream, fmt, ...)
	{vkSscanf, 2},   // sscanf(str, fmt, ...)
	{vkFscanf, 2},   // fscanf(stream, fmt, ...)
	{vkScanf, 1},    // scanf(fmt, ...)
	{vkSyslog, 2},   // syslog(priority, fmt, ...)
}

var variadicNames = []string{"snprintf", "sprintf", "printf", "fprintf", "sscanf", "fscanf", "scanf", "syslog"}

var variadicID = func() map[string]int {
	m := make(map[string]int, len(variadicNames))
	for i, n := range variadicNames {
		m[n] = i
	}
	return m
}()

// goVariadic is called from variadicEntry with the saved register state.
//
//go:noinline
func goVariadic(id, save, overflow uintptr) int {
	if int(id) >= len(variadicDescs) {
		return 0
	}
	d := variadicDescs[id]
	v := &vaList{gpOffset: 0, fpOffset: 48, overflow: overflow, regSave: save}

	var fixed [3]uintptr
	for i := 0; i < d.fixedGP; i++ {
		fixed[i] = uintptr(v.gp())
	}

	switch d.kind {
	case vkSnprintf:
		out := formatC(cstr(fixed[2]), v)
		return copyOutBounded(fixed[0], fixed[1], out)
	case vkSprintf:
		out := formatC(cstr(fixed[1]), v)
		copyToGuest(fixed[0], out)
		*(*byte)(unsafe.Pointer(fixed[0] + uintptr(len(out)))) = 0
		return len(out)
	case vkPrintf:
		out := formatC(cstr(fixed[0]), v)
		return writeStream(stdoutPtr, out)
	case vkFprintf:
		out := formatC(cstr(fixed[1]), v)
		return writeStream(fixed[0], out)
	case vkSscanf:
		return runSscanf(fixed[0], fixed[1], v)
	case vkFscanf:
		return runFscanf(fixed[0], fixed[1], v)
	case vkScanf:
		return runFscanf(stdinPtr, fixed[0], v)
	case vkSyslog:
		out := formatC(cstr(fixed[1]), v)
		writeStderrRaw(fmt.Sprintf("rbxrt: syslog<%d>: %s\n", int32(fixed[0]), out))
		return 0
	}
	return 0
}

func copyOutBounded(str, size uintptr, out []byte) int {
	n := len(out)
	if size != 0 {
		limit := int64(size) - 1
		c := int64(n)
		if c > limit {
			c = limit
		}
		if c > 0 {
			copyToGuest(str, out[:c])
		}
		*(*byte)(unsafe.Pointer(str + uintptr(c))) = 0
	}
	return n
}

func writeStream(stream uintptr, out []byte) int {
	cf := lookupFile(stream)
	if cf == nil {
		return -1
	}
	return fileWrite(cf, out)
}

// mkVariadicThunk writes a thunk that sets R10 to id and jumps to the raw
// variadicEntry body. The jump is indirect through an inline 8-byte absolute
// address ([RIP]+0): a rel32 JMP cannot reach across the distance between the
// executable code arena (mmap'd near the guest) and the Go text segment.
func mkVariadicThunk(id int) uintptr {
	b := codeArena(32)
	off := 0
	// MOVQ $id, R10
	b[off] = 0x49
	b[off+1] = 0xBA
	off += 2
	put64(b[off:], uintptr(id))
	off += 8
	// JMP [RIP+0] — falls through to the 8-byte absolute target slot below.
	b[off] = 0xFF
	b[off+1] = 0x25
	off += 2
	put32(b[off:], 0)
	off += 4
	put64(b[off:], variadicEntryAddr())
	off += 8
	return uintptr(unsafe.Pointer(&b[0]))
}

func put32(b []byte, v uint32) {
	b[0] = byte(v)
	b[1] = byte(v >> 8)
	b[2] = byte(v >> 16)
	b[3] = byte(v >> 24)
}

// --- va_list-taking entry points (not variadic themselves) ---------------

// goVfprintf implements vfprintf(FILE *stream, const char *fmt, va_list ap).
//
//go:noinline
func goVfprintf(stream, format, ap uintptr) int {
	out := formatC(cstr(format), (*vaList)(unsafe.Pointer(ap)))
	return writeStream(stream, out)
}

// goVprintf implements vprintf(const char *fmt, va_list ap).
//
//go:noinline
func goVprintf(format, ap uintptr) int {
	out := formatC(cstr(format), (*vaList)(unsafe.Pointer(ap)))
	return writeStream(stdoutPtr, out)
}

// goVsprintfChk implements __vsprintf_chk(str, flag, slen, fmt, ap).
//
//go:noinline
func goVsprintfChk(str, flag, slen, format, ap uintptr) int {
	_ = flag
	_ = slen
	return goVsprintf(str, format, ap)
}
